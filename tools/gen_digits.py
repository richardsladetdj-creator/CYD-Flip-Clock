#!/usr/bin/env python3
"""Render digits 0-9 into card-sized 4-bit alpha bitmaps -> include/digits.h

usage: python gen_digits.py BebasNeue-Regular.ttf ../include/digits.h   (needs Pillow)
"""
import sys
from PIL import Image, ImageDraw, ImageFont

W, H = 70, 200          # card cell size, must match layout in main.cpp
MAX_W, MAX_H = 62, 172  # glyph box inside the card
SY = 1.35               # vertical stretch: condensed digits fill the tall card (1.0 = none)

font_path, out_path = sys.argv[1], sys.argv[2]

# grow the font until the widest/tallest digit hits the box
size = 50
while True:
    f = ImageFont.truetype(font_path, size + 1)
    boxes = [f.getbbox(str(d)) for d in range(10)]
    if max(b[2] - b[0] for b in boxes) > MAX_W or max(b[3] - b[1] for b in boxes) * SY > MAX_H:
        break
    size += 1
font = ImageFont.truetype(font_path, size)
boxes = [font.getbbox(str(d)) for d in range(10)]
top = min(b[1] for b in boxes)
bot = max(b[3] for b in boxes)
HR = round(H / SY)      # render height before stretch
oy = (HR - (bot - top)) // 2 - top  # shared baseline, vertically centred

rows = []
for d in range(10):
    b = boxes[d]
    img = Image.new("L", (W, HR), 0)
    ImageDraw.Draw(img).text(((W - (b[2] - b[0])) // 2 - b[0], oy), str(d), fill=255, font=font)
    px = img.resize((W, H), Image.LANCZOS).tobytes()
    packed = bytes((px[i] >> 4) << 4 | (px[i + 1] >> 4) for i in range(0, len(px), 2))
    rows.append(packed)

with open(out_path, "w") as o:
    o.write(f"// generated by tools/gen_digits.py from {font_path.split('/')[-1]} @ {size}px - do not edit\n")
    o.write("#pragma once\n#include <stdint.h>\n")
    o.write(f"#define DIG_W {W}\n#define DIG_H {H}\n")
    o.write(f"static const uint8_t DIGITS[10][{W * H // 2}] = {{\n")
    for p in rows:
        o.write("{" + ",".join(str(v) for v in p) + "},\n")
    o.write("};\n")
print("font size", size)
